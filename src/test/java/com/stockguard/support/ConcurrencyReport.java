package com.stockguard.support;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.time.OffsetDateTime;
import java.time.temporal.ChronoUnit;

/**
 * Collects what the tests actually measured into target/concurrency-report/report.md. CI publishes this file,
 * and docs/concurrency.md quotes it, so reported numbers always come from a real run.
 */
public final class ConcurrencyReport {

    private static final Path FILE = Path.of("target", "concurrency-report", "report.md");
    private static boolean started;

    private ConcurrencyReport() {
    }

    public static synchronized void add(String scenario, String measured) {
        try {
            if (!started) {
                Files.createDirectories(FILE.getParent());
                Files.writeString(FILE, """
                        # StockGuard concurrency report

                        Generated by the integration tests on %s, Java %s, %s, %d CPU(s), PostgreSQL image `%s`.

                        | Scenario | Measured |
                        |---|---|
                        """.formatted(
                        OffsetDateTime.now().truncatedTo(ChronoUnit.SECONDS),
                        System.getProperty("java.version"),
                        System.getProperty("os.name"),
                        Runtime.getRuntime().availableProcessors(),
                        TestPostgres.IMAGE));
                started = true;
            }
            Files.writeString(FILE, "| " + scenario + " | " + measured + " |\n", StandardOpenOption.APPEND);
        } catch (IOException ex) {
            throw new UncheckedIOException(ex);
        }
    }
}
